"""Trim renders, export WebP with alpha, and write src/data/sprites.ts.

usage: python3 scripts/sprites/process_sprites.py <render-root> <repo-root>
"""
import json, math, os, sys
from PIL import Image

S, REPO = sys.argv[1], sys.argv[2]
OUT = os.path.join(REPO, 'public', 'sprites')
os.makedirs(OUT, exist_ok=True)

FOV = 20
def units_across(d): return 2 * d * math.tan(math.radians(FOV / 2))
PIECE_PX, PIECE_DIST = 512, 1.2
BOWL_PX, BOWL_DIST = 1024, 8.2
piece_ppu = PIECE_PX / units_across(PIECE_DIST)   # render px per world unit
bowl_ppu = BOWL_PX / units_across(BOWL_DIST)
TARGET_PPU = 520                                   # ~2x density for a 640px-wide bowl on screen

def bbox(im, thr=6):
    a = im.split()[-1].point(lambda v: 255 if v > thr else 0)
    return a.getbbox()

manifest = {'bowl': {}, 'pieces': {}, 'props': {}}

# --- bowl layers share one crop -------------------------------------------
bowl_dir = os.path.join(S, 'bowl')
back = Image.open(os.path.join(bowl_dir, 'back.png')).convert('RGBA')
x0, y0, x1, y1 = bbox(back)
pad = 40
# leave headroom above the bowl for pieces falling in
crop = (max(0, x0 - pad), max(0, y0 - pad * 4), min(BOWL_PX, x1 + pad), min(BOWL_PX, y1 + pad))
cw, ch = crop[2] - crop[0], crop[3] - crop[1]
scale = min(1.0, TARGET_PPU / bowl_ppu)
manifest['bowl'] = {
    'crop': {'x': crop[0], 'y': crop[1], 'w': cw, 'h': ch},
    'renderPx': BOWL_PX,
    'width': round(cw * scale), 'height': round(ch * scale),
    'unitsWide': cw / bowl_ppu,
    'layers': {},
}
for f in sorted(os.listdir(bowl_dir)):
    if not f.endswith('.png') or f == 'sheet.png':
        continue
    name = f[:-4]
    im = Image.open(os.path.join(bowl_dir, f)).convert('RGBA').crop(crop)
    im = im.resize((round(cw * scale), round(ch * scale)), Image.LANCZOS)
    im.save(os.path.join(OUT, f'bowl-{name}.webp'), 'WEBP', quality=86, method=6)
    manifest['bowl']['layers'][name] = f'/sprites/bowl-{name}.webp'

# --- ingredient pieces -----------------------------------------------------
pdir = os.path.join(S, 'pieces')
if os.path.isdir(pdir):
    DIST = {'icecream-scoop': 2.2, 'plant-protein': 2.0, 'whey-protein': 2.0}
    for f in sorted(os.listdir(pdir)):
        if not f.endswith('.png'):
            continue
        name = f[:-4]            # e.g. strawberry-0-1  (id-kind-variant)
        im = Image.open(os.path.join(pdir, f)).convert('RGBA')
        b = bbox(im)
        if not b:
            print('empty', f); continue
        b = (max(0, b[0] - 2), max(0, b[1] - 2), min(PIECE_PX, b[2] + 2), min(PIECE_PX, b[3] + 2))
        w, h = b[2] - b[0], b[3] - b[1]
        idd, kind, var = name.rsplit('-', 2)
        ppu = PIECE_PX / units_across(DIST.get(idd, PIECE_DIST))
        k = min(1.0, TARGET_PPU / ppu)
        out = im.crop(b).resize((max(1, round(w * k)), max(1, round(h * k))), Image.LANCZOS)
        out.save(os.path.join(OUT, f'{name}.webp'), 'WEBP', quality=88, method=6)
        manifest['pieces'].setdefault(idd, []).append({
            'src': f'/sprites/{name}.webp', 'kind': int(kind), 'variant': int(var),
            # size in world units and the object origin's position inside the image (0..1)
            'w': w / ppu, 'h': h / ppu,
            'ox': (PIECE_PX / 2 - b[0]) / w, 'oy': (PIECE_PX / 2 - b[1]) / h,
        })

# --- scanned props (arbitrary scale) --------------------------------------
rdir = os.path.join(S, 'props')
if os.path.isdir(rdir):
    for f in sorted(os.listdir(rdir)):
        if not f.endswith('.png'):
            continue
        im = Image.open(os.path.join(rdir, f)).convert('RGBA')
        b = bbox(im)
        out = im.crop(b)
        if out.width > 420:
            out = out.resize((420, round(out.height * 420 / out.width)), Image.LANCZOS)
        out.save(os.path.join(OUT, f'prop-{f[:-4]}.webp'), 'WEBP', quality=86, method=6)
        manifest['props'][f[:-4]] = {'src': f'/sprites/prop-{f[:-4]}.webp', 'w': out.width, 'h': out.height}

ts = '''/* Generated by the sprite pipeline (dev/sprites + process_sprites.py). Do not edit by hand. */

export interface PieceSprite {
  src: string;
  kind: number;
  variant: number;
  /** Size in world units (1 unit = 7.5 cm). */
  w: number;
  h: number;
  /** Where the piece's centre sits inside the image (fractions). */
  ox: number;
  oy: number;
}

export const SPRITES = ''' + json.dumps(manifest, indent=2) + ''' as const;

export const PIECES = SPRITES.pieces as unknown as Record<string, PieceSprite[]>;
'''
open(os.path.join(REPO, 'src', 'data', 'sprites.ts'), 'w').write(ts)
total = sum(os.path.getsize(os.path.join(OUT, x)) for x in os.listdir(OUT))
print('sprites', len(os.listdir(OUT)), 'files', round(total / 1024), 'KB')
